def get_search_terms(content_type: str) -> list[str]:
    """获取某违规类型的所有合法检索词（供 Step-Back LLM 输出校验）。

    若 content_type 不在 TAXONOMY 中，回退到 other_violation。
    """
    entry = TAXONOMY.get(content_type, TAXONOMY["other_violation"])
    return entry["search_terms"]


def get_step_back_query(content_type: str) -> str:
    """获取预置的 Step-Back 抽象查询（LLM 失败时的回退，不调 LLM）。"""
    entry = TAXONOMY.get(content_type, TAXONOMY["other_violation"])
    return entry["step_back_query"]


def get_domain_hint(content_type: str) -> str:
    """格式化法律领域 + 检索词列表，注入 Step-Back prompt 约束 LLM 输出空间。"""
    entry = TAXONOMY.get(content_type, TAXONOMY["other_violation"])
    terms_str = "\n".join(f"  - {t}" for t in entry["search_terms"])
    return f"法律领域：{entry['domain']}\n可用检索词（只能从以下选择）：\n{terms_str}"
